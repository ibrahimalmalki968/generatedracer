export const translations = Object.freeze({
  en: Object.freeze(Object.fromEntries(entries.map(([key, en]) => [key, en]))),
  ar: Object.freeze(Object.fromEntries(entries.map(([key, , ar]) => [key, ar]))),
});
export const DEFAULT_LANGUAGE = 'ar';
export const supportedLanguage = value => value === 'ar' || value === 'en';
export const isTranslationKey = key => Object.prototype.hasOwnProperty.call(translations.en, key);
export const missingTranslations = new Set();
const rules = { ar: new Intl.PluralRules('ar'), en: new Intl.PluralRules('en') };
export function translate(language, key, params = {}) {
  const locale = supportedLanguage(language) ? language : DEFAULT_LANGUAGE;
  let value = Object.prototype.hasOwnProperty.call(translations[locale], key) ? translations[locale][key] : isTranslationKey(key) ? translations.en[key] : undefined;
  if (value === undefined) { missingTranslations.add(key); value = translations[locale]['error.unknown']; }
  if (typeof value === 'object') value = value[rules[locale].select(Number(params.count))] ?? value.other;
  return value.replace(/\{(\w+)\}/g, (_, name) => {
    const text = String(params[name] ?? '');
    if (['name', 'names'].includes(name) && (locale === 'ar' || /[\u0590-\u08ff]/.test(text))) return '\u2068' + text + '\u2069';
    return locale === 'ar' && ['time', 'best', 'version'].includes(name) ? '\u2066' + text + '\u2069' : text;
  });
}
export const message = (key, params = {}) => ({ key, params });
export class MessageError extends Error {
  constructor(key, params = {}) { super(translate('en', key, params)); this.code = key; this.params = params; }
}
export const fault = (key, params) => new MessageError(key, params);
