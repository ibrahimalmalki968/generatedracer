// Copy the deployable app without introducing a frontend bundler.
import { cp, mkdir, readFile, writeFile, access, rm } from 'node:fs/promises';
import { resolve, sep } from 'node:path';
import { fileURLToPath } from 'node:url';
import { spawnSync } from 'node:child_process';

const root = fileURLToPath(new URL('../', import.meta.url));
const target = resolve(root, 'dist');
if (!target.startsWith(resolve(root) + sep) || target !== resolve(root, 'dist')) throw new Error('Unsafe build target.');
let exists = false;
try { await access(target); exists = true; } catch { /* first build */ }
if (exists) {
  try { await access(resolve(target, '.generatedracer-build')); }
  catch { throw new Error('dist already exists without a GenerateRacer build marker. Build stopped to preserve its contents.'); }
  await rm(target, { recursive: true }); // checked generated directory only
}
await mkdir(target);
await writeFile(resolve(target, '.generatedracer-build'), 'Generated by tools/build.mjs\n');
const files = ['server/server.js', 'server/game.js', 'server/static.js', 'shared/protocol.js', 'js/main.js', 'js/network.js', 'js/lobby.js'];
for (const file of files) {
  const result = spawnSync(process.execPath, ['--check', resolve(root, file)], { encoding: 'utf8' });
  if (result.status !== 0) throw new Error(`Syntax check failed: ${file}\n${result.stderr}`);
}
for (const file of ['index.html', 'game.css', 'assets', 'LICENSE', 'package.json', 'package-lock.json', 'js', 'shared', 'server']) {
  await cp(resolve(root, file), resolve(target, file), { recursive: true });
}
const packageJson = JSON.parse(await readFile(resolve(target, 'package.json')));
if (packageJson.scripts.start !== 'node server/server.js') throw new Error('Build is missing the authoritative server entry point.');
console.log(`Built ${target}. Run npm ci --omit=dev --ignore-scripts and npm start from this directory.`);
